# Собирает docs/questions.md — читаемую копию банка по сферам — из src/questions/bank.json.
# Запуск: python3 scripts/questions-doc.py
import json, re, os
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
bank = json.load(open(f'{R}/src/questions/bank.json')); qs = bank['questions']
sph = re.findall(r"\{ id: '(\w+)', block: '(\w+)', label: '([^']+)'", open(f'{R}/src/questions/spheres.ts').read())
blocks = [('friendship', 'Блок «Партнёр как друг»'), ('relationship', 'Блок «Отношения»'), ('maturity', 'Блок «Эмоциональная зрелость»')]
n = {b: sum(1 for q in qs if q['block'] == b) for b, _ in blocks}
out = [f"""# Банк вопросов

Источник правды — `src/questions/bank.json` (версия {bank['version']}); этот файл — читаемая копия по сферам, собирается `python3 scripts/questions-doc.py`.
{len(qs)} вопросов, тест только для пар: «Партнёр как друг» — {n['friendship']}, «Отношения» — {n['relationship']}, «Эмоциональная зрелость» — {n['maturity']} (в конце теста, на проценты не влияет). 🔒 — можно пропустить. ⚑ — под вариантами отметка «Для меня это не обсуждается»: красный флаг ставится только по ней (кто-то из пары отметил, а ответы расходятся через вариант и дальше).

С версии 14 вместо шкалы 0–10 — 5 вариантов словами. Совпадение — по таблице 5×5 (`MATCH` в `src/scoring/primitives.ts`).

## Принципы составления

1. **Одна ось, плавный переход.** 5 вариантов — по одному критерию от левого края к правому, каждый на шаг дальше предыдущего; соседние варианты заметно различаются.
2. **Полюса взаимоисключающие.** Нельзя честно оказаться на обоих краях («ем что хочу» не противоположно «слежу за питанием»).
3. **Середина — позиция, а не «зависит».** Третий вариант — настоящая середина оси.
4. **Ответ зависит только от того, что в вопросе.** Ситуация задана настолько, чтобы ответ не зависел от частоты, силы повода, дохода или нескольких причин сразу; если причин несколько — вопрос разбивается.
5. **Одна конкретная ситуация, а не широкая категория.** «Шутки о трагедиях» включают и насмешку над людьми, и иронию о далёком событии — человек отвечает про тот пример, который представил. Берётся один понятный случай.
6. **Не смешивать отношение и действие.** Все варианты одного вопроса — либо о чувствах, либо о поступках.
7. **Без «правильного» ответа.** Оба края звучат приемлемо, без оценочных слов; «одобряемый» край то слева, то справа.
8. **Только значимое.** Каждая тема — такая, где расхождение реально влияет на отношения. Красный флаг — только по явной отметке «не обсуждается» (⚑).
9. **Без повторов и с нейтральным родом.** Везде «партнёр»; «друг» — только третье лицо; «мужчина/женщина» — только в вопросах о ролях.
"""]
for b, title in blocks:
    out.append(f"\n## {title}\n")
    for sid, sb, label in sph:
        if sb != b: continue
        items = [q for q in qs if q['sphere'] == sid]
        out.append(f"\n### {label} — {len(items)}\n")
        for q in items:
            mark = (' 🔒' if q['optional'] else '') + (' ⚑' if q.get('firm') else '') + (' (на проценты не влияет)' if q.get('scored') is False else '')
            out.append(f"\n**{q['id']}{mark}** — {q['text']} · _{q['topic']}_\n")
            out.extend(f"{i+1}. {o}\n" for i, o in enumerate(q['options']))
open(f'{R}/docs/questions.md', 'w').write(''.join(out))
print('docs/questions.md:', len(qs), 'вопросов')
