import { h } from '../dom';
import { shareBlock } from '../share';

export function finishScreen(url: string, onPartnerHere: () => void): HTMLElement {
  return h('section', { class: 'screen' },
    h('h1', {}, 'Готово!'),
    h('p', {}, 'Отправьте ссылку партнёру. Когда вы оба полностью пройдёте тест, вы увидите совместимость, ответы друг друга и краткие описания по вашим ответам. Партнёр сможет отправить результат вам. Если он уже прошёл тест сам, пусть откроет вашу ссылку на том же устройстве — сохранённые ответы не придётся вводить заново.'),
    shareBlock(url, 'Тест совместимости'),
    h('h3', {}, 'Партнёр рядом?'),
    h('p', { class: 'hint' }, 'Он может пройти тест прямо здесь, на этом устройстве. Результат сохранится на главной в «Ваших результатах».'),
    h('button', { type: 'button', class: 'secondary', onclick: () => onPartnerHere() }, 'Пройти тест партнёру здесь'),
  );
}
