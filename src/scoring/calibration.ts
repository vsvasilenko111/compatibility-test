/**
 * Калибровка процентов совместимости. Сырой процент из compare() у случайных незнакомцев в среднем ~59%, поэтому
 * показывается его место среди случайных пар: 50% — типичная случайная пара, 90% — лучше 9 из 10 случайных пар.
 * Таблицы — сырой процент на процентилях 0, 5, …, 100 по 870 случайным парам синтетического прогона (30 пар, 60 персонажей; банк v8 — блок дружбы о партнёре, вопросы о детях без привязки к возрасту, юмор/вера/досуг/темп, «амбиции через 10 лет» не считаются; персонажи переответили на 67 изменённых и новых вопросов, веса сфер в отношениях и в «партнёр как друг», мягкая разница по одну сторону от середины).
 * При появлении реальных данных пересчитать.
 */
