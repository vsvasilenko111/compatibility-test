/**
 * Калибровка процентов совместимости. Сырой процент из compare() у случайных незнакомцев в среднем ~59%, поэтому
 * показывается его место среди случайных пар: 50% — типичная случайная пара, 90% — лучше 9 из 10 случайных пар.
 * Таблицы — сырой процент на процентилях 0, 5, …, 100 по 870 случайным парам синтетического прогона (30 пар, 60 персонажей; банк v6 — блок дружбы о партнёре, «амбиции через 10 лет» не считаются; персонажи переответили на 67 изменённых и новых вопросов, веса сфер в отношениях, мягкая разница по одну сторону от середины).
 * При появлении реальных данных пересчитать.
 */
export const RELATIONSHIP_TABLE: readonly number[] = [13.1,35.2,41.7,45.3,48.9,52.4,54.9,57.9,60.5,63,66.4,69.6,72.1,74.2,76.3,78.2,79.9,81.4,82.9,85.4,93.3];
export const FRIENDSHIP_TABLE: readonly number[] = [22.5,36.5,44.1,50.9,54.5,58.1,60.4,63.2,65.9,68.8,70.6,72.5,74.5,76.3,78,80.1,81.9,84,85.9,87.4,94];

/** Сырой процент → откалиброванный 0..100 (линейная интерполяция между процентилями таблицы). */
export function calibrate(raw: number | null, table: readonly number[]): number | null {
  if (raw === null) return null;
  const last = table.length - 1;
  if (raw <= table[0]) return 0;
  if (raw >= table[last]) return 100;
  for (let i = 1; i <= last; i++) {
    if (raw <= table[i]) {
      const span = table[i] - table[i - 1];
      const t = span > 0 ? (raw - table[i - 1]) / span : 1;
      return ((i - 1 + t) / last) * 100;
    }
  }
  return 100;
}
