/**
 * Калибровка процентов совместимости. Сырой процент из compare() у случайных незнакомцев в среднем ~59%, поэтому
 * показывается его место среди случайных пар: 50% — типичная случайная пара, 90% — лучше 9 из 10 случайных пар.
 * Таблицы — сырой процент на процентилях 0, 5, …, 100 по 870 случайным парам синтетического прогона (30 пар, 60 персонажей; банк v7 — блок дружбы о партнёре, вопросы о детях без привязки к возрасту, «амбиции через 10 лет» не считаются; персонажи переответили на 67 изменённых и новых вопросов, веса сфер в отношениях и в «партнёр как друг», мягкая разница по одну сторону от середины).
 * При появлении реальных данных пересчитать.
 */
export const RELATIONSHIP_TABLE: readonly number[] = [14.8,33.8,41,45.4,49.7,52.7,55.4,58.3,60.4,63.3,66,68.6,71,72.9,74.9,77,78.9,80.8,82.5,85,92.9];
export const FRIENDSHIP_TABLE: readonly number[] = [22.2,37.7,47.1,51.6,55.4,58.3,60.5,63.7,66.2,68.1,69.8,72.1,73.8,75.5,77.8,79.1,80.8,82.7,84.9,87,93.4];

/** Сырой процент → откалиброванный 0..100 (линейная интерполяция между процентилями таблицы). */
export function calibrate(raw: number | null, table: readonly number[]): number | null {
  if (raw === null) return null;
  const last = table.length - 1;
  if (raw <= table[0]) return 0;
  if (raw >= table[last]) return 100;
  for (let i = 1; i <= last; i++) {
    if (raw <= table[i]) {
      const span = table[i] - table[i - 1];
      const t = span > 0 ? (raw - table[i - 1]) / span : 1;
      return ((i - 1 + t) / last) * 100;
    }
  }
  return 100;
}
